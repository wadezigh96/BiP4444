#!/usr/bin/env node
/**
 * BIP4444 Alert Shield — example publisher (Node.js)
 *
 * Usage (private key from env, never committed):
 *   ALERT_PUBLISHER_PRIVATE_KEY=<base64-or-hex-or-pem> node scripts/alert-publisher-example.js
 *
 * This script demonstrates how a server would sign an alert.
 * It does NOT contain any private key.
 *
 * Expected env:
 *   ALERT_PUBLISHER_PRIVATE_KEY  — Ed25519 private key (PKCS8 PEM, raw hex, or raw base64)
 *   ALERT_PUBLIC_KEY_ID          — matches an entry in the key directory (default: demo-publisher-2026-10-21)
 */

const crypto = require("crypto");
const fs = require("fs");

function loadPrivateKey() {
  const raw = process.env.ALERT_PUBLISHER_PRIVATE_KEY;
  if (!raw) {
    console.error("Set ALERT_PUBLISHER_PRIVATE_KEY (never commit it)");
    process.exit(1);
  }
  // Support PEM or raw
  if (raw.includes("BEGIN")) {
    return crypto.createPrivateKey(raw);
  }
  // Assume hex or base64 raw 32-byte seed — wrap as PKCS8 if needed
  // For simplicity, expect PEM in production. Demo path below.
  throw new Error("Provide private key as PEM (PKCS8). Raw seed wrapping is left as an exercise.");
}

function signPayload(payload, privateKey) {
  const json = JSON.stringify(payload);
  const sig = crypto.sign(null, Buffer.from(json), privateKey);
  return sig.toString("base64");
}

const payload = {
  alertId: `alert-${Date.now()}`,
  severity: "S1",
  title: "Example signed alert",
  summary: "Generated by scripts/alert-publisher-example.js",
  guidance: ["Verify against key directory", "Trust only official domain links"],
  uncertainty: "Example only",
  affectedScope: "None",
  links: ["https://bips4444.vercel.app/"],
  publishedAt: new Date().toISOString(),
  expiresAt: new Date(Date.now() + 7 * 24 * 60 * 60 * 1000).toISOString(),
  reporterId: process.env.ALERT_PUBLIC_KEY_ID || "demo-publisher-2026-10-21",
};

try {
  const privateKey = loadPrivateKey();
  const signature = signPayload(payload, privateKey);
  const envelope = {
    payload,
    signatures: [
      {
        publicKeyId: process.env.ALERT_PUBLIC_KEY_ID || "demo-publisher-2026-10-21",
        signature,
      },
    ],
  };
  console.log(JSON.stringify(envelope, null, 2));
} catch (e) {
  console.error(e.message);
  process.exit(1);
}
